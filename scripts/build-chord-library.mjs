// Builds src/render/header/guitarChords.ts, the chord library, from the guitar data of
// chords-db by Tabsy (https://github.com/tabsy-gr/chords-db, MIT, see THIRD_PARTY_NOTICES.md).
//
// The data is pinned to one commit. To rebuild, or to move to a newer commit (update COMMIT):
//   curl -sfLo /tmp/guitar.json https://raw.githubusercontent.com/tabsy-gr/chords-db/<COMMIT>/lib/guitar.json
//   npm run build:chords -- /tmp/guitar.json
//
// Each fingering becomes one short string: 6 frets low E to high E (hex, `x` muted), 6 fingers
// (`0` none, `1`–`4`, `T` thumb), then the frets held by a barre (hex). Frets are absolute.
// Fingering ids, sources, MIDI notes and the capo flag are not kept.

import { readFileSync, writeFileSync } from 'node:fs';

const COMMIT = '43f8b4a7ba7b61b90bb48f8721ae918a4f421d64';
const OUT = 'src/render/header/guitarChords.ts';
const STRINGS = 6;

const input = process.argv[2];
if (!input) {
	console.error('Usage: npm run build:chords -- <path to lib/guitar.json>');
	process.exit(1);
}

const data = JSON.parse(readFileSync(input, 'utf8'));
if (data.instrument?.id !== 'guitar') throw new Error('Not the guitar data of chords-db.');

const hex = (fret) => {
	if (!Number.isInteger(fret) || fret < 0 || fret > 15) throw new Error(`Fret out of range: ${fret}`);
	return fret.toString(16);
};

function encode(voicing, where) {
	const { frets, fingers, barres = [] } = voicing;
	if (frets.length !== STRINGS || fingers.length !== STRINGS) throw new Error(`${where}: not ${STRINGS} strings`);
	const fretText = frets.map((fret) => (fret === -1 ? 'x' : hex(fret))).join('');
	const fingerText = fingers
		.map((finger) => {
			if (finger === 'T' || (Number.isInteger(finger) && finger >= 0 && finger <= 4)) return String(finger);
			throw new Error(`${where}: finger ${finger}`);
		})
		.join('');
	return fretText + fingerText + barres.map(hex).join('');
}

const lines = [];
let count = 0;
for (const key of data.instrument.keys) {
	for (const chord of data.chords[key] ?? []) {
		if (/\s/.test(chord.key + chord.suffix)) throw new Error(`Space in ${chord.key} ${chord.suffix}`);
		const voicings = chord.voicings.map((voicing) => encode(voicing, voicing.id));
		count += voicings.length;
		lines.push(`\t'${chord.key} ${chord.suffix} ${voicings.join(' ')}',`);
	}
}

const source = `// Generated by scripts/build-chord-library.mjs: do not edit.
// Guitar fingerings from chords-db by Tabsy, https://github.com/tabsy-gr/chords-db, commit
// ${COMMIT}. MIT License, see THIRD_PARTY_NOTICES.md.
//
// One chord per entry: its key, its suffix, then its fingerings in the library's order. A
// fingering is 6 frets from low E (hex, x muted), 6 fingers (0 none, 1-4, T thumb), then the
// frets held by a barre (hex).

export const GUITAR_CHORDS: readonly string[] = [
${lines.join('\n')}
];
`;
writeFileSync(OUT, source);
console.log(`${OUT}: ${lines.length} chords, ${count} fingerings, ${source.length} bytes`);
