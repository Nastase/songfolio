import esbuild from 'esbuild';
import process from 'process';
import { builtinModules } from 'node:module';
import { copyFileSync, existsSync, mkdirSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

const banner = `/*
THIS IS A GENERATED/BUNDLED FILE BY ESBUILD
if you want to view the source, please visit the github repository of this plugin
*/
`;

const prod = process.argv[2] === 'production';

// In dev mode the plugin is built straight into the dev vault, with a
// .hotreload marker so the Hot Reload plugin reloads it on every rebuild.
const devPluginDir = 'dev-vault/.obsidian/plugins/songfolio';
const outfile = prod ? 'main.js' : join(devPluginDir, 'main.js');

/** Copies manifest.json and styles.css next to the dev build after each rebuild. */
const copyToDevVault = {
	name: 'copy-to-dev-vault',
	setup(build) {
		build.onEnd((result) => {
			if (result.errors.length > 0) return;
			mkdirSync(devPluginDir, { recursive: true });
			for (const file of ['manifest.json', 'styles.css']) {
				if (existsSync(file)) copyFileSync(file, join(devPluginDir, file));
			}
			writeFileSync(join(devPluginDir, '.hotreload'), '');
		});
	},
};

const context = await esbuild.context({
	banner: {
		js: banner,
	},
	entryPoints: ['src/main.ts'],
	bundle: true,
	external: [
		'obsidian',
		'electron',
		'@codemirror/autocomplete',
		'@codemirror/collab',
		'@codemirror/commands',
		'@codemirror/language',
		'@codemirror/lint',
		'@codemirror/search',
		'@codemirror/state',
		'@codemirror/view',
		'@lezer/common',
		'@lezer/highlight',
		'@lezer/lr',
		...builtinModules,
	],
	format: 'cjs',
	target: 'es2021',
	logLevel: 'info',
	sourcemap: prod ? false : 'inline',
	treeShaking: true,
	outfile,
	minify: prod,
	plugins: prod ? [] : [copyToDevVault],
});

if (prod) {
	await context.rebuild();
	process.exit(0);
} else {
	await context.watch();
}
